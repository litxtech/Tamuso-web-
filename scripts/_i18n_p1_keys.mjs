function esc(s) {
  return String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
}

function serializeSection(name, obj, indent = 2) {
  const pad = ' '.repeat(indent);
  const padIn = ' '.repeat(indent + 2);
  const entries = Object.entries(obj);
  const lines = entries.map(([k, v], i) => {
    const comma = i < entries.length - 1 ? ',' : '';
    return `${padIn}${k}: '${esc(v)}'${comma}`;
  });
  return `${pad}${name}: {\n${lines.join('\n')}\n${pad}}`;
}

function inject(localePath, sections, isTr) {
  let src = fs.readFileSync(localePath, 'utf8');
  // Remove old injected sections if re-run
  for (const name of Object.keys(sections)) {
    const re = new RegExp(`\\n  ${name}: \\{[\\s\\S]*?\\n  \\},?`, 'g');
    src = src.replace(re, '\n');
  }
  const block =
    '\n' +
    Object.entries(sections)
      .map(([name, obj]) => serializeSection(name, obj) + ',')
      .join('\n') +
    '\n';
  if (!src.includes('\n  genel:')) {
    throw new Error('genel section not found in ' + localePath);
  }
  src = src.replace('\n  genel:', block + '\n  genel:');
  // Fix double commas / trailing before genel
  src = src.replace(/,\s*,\n  genel:/, ',\n  genel:');
  fs.writeFileSync(localePath, src, 'utf8');
  console.log('patched', localePath, Object.keys(sections).join(','));
}

