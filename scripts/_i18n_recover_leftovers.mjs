function appendBefore(src, anchorLine, block) {
  if (src.includes('davetlerAlt:')) return src; // already recovered
  const idx = src.indexOf(anchorLine);
  if (idx < 0) throw new Error('anchor not found: ' + anchorLine);
  const end = idx + anchorLine.length;
  return src.slice(0, end) + block + src.slice(end);
}

function appendNs(src, nsCloseAnchor, block, alreadyKey) {
  if (src.includes(alreadyKey)) return src;
  const idx = src.indexOf(nsCloseAnchor);
  if (idx < 0) throw new Error('ns anchor not found: ' + nsCloseAnchor);
  return src.slice(0, idx) + block + src.slice(idx);
}

